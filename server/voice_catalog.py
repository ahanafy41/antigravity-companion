def get_voice_catalog():
    """Return copy of prebuilt voices list."""
    return [dict(v) for v in PREBUILT_VOICES]


def find_voice(voice_name):
    """Find voice by name or id (case-insensitive)."""
    if not voice_name:
        return find_voice(DEFAULT_VOICE)
    target = voice_name.strip().lower()
    for v in PREBUILT_VOICES:
        if v["name"].lower() == target or v["id"] == target:
            return dict(v)
    return find_voice(DEFAULT_VOICE)
